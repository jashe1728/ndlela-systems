import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CLIENTS_DIR, loadClientsFromDisk } from '../server/local-dev.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const OUTPUT_FILE = path.join(__dirname, 'clients.generated.mjs');

const clients = await loadClientsFromDisk(CLIENTS_DIR);
const banner = '// Auto-generated by chatbot/worker/bundle-clients.mjs. Do not edit manually.\n';
const output = `${banner}export const CLIENTS = ${JSON.stringify(clients, null, 2)};\n`;

await fs.writeFile(OUTPUT_FILE, output, 'utf8');
console.log(`Bundled ${Object.keys(clients).length} client pack(s) into ${OUTPUT_FILE}: ${Object.keys(clients).join(', ')}`);
